<?php
	namespace KrameWork\Users\Schema;

	use KrameWork\Database\Driver\Generic;
	use KrameWork\Database\Schema\IMetaTable;
	use KrameWork\Database\Schema\TableVersion;

	require_once(__DIR__ . '/UserManagedTable.php');
	require_once(__DIR__ . '/DatabaseType.php');
	require_once(__DIR__ . '/../../Database/Schema/TableVersion.php');

	/**
	 * Class UserAccountsTable
	 * Managed table for user accounts. The table holds only the columns that the user system uses.
	 *
	 * @package KrameWork\Users\Schema
	 */
	class UserAccountsTable extends UserManagedTable
	{
		/**
		 * UserAccountsTable constructor.
		 *
		 * @api __construct
		 * @param Generic $db Database connection.
		 * @param IMetaTable $metaTable Meta table that stores the table versions.
		 * @param DatabaseType $type Type of the database. It sets the SQL for the auto-increment ID column.
		 */
		public function __construct(Generic $db, IMetaTable $metaTable, private DatabaseType $type) {
			parent::__construct($db, $metaTable);
		}

		/**
		 * Returns the name of the table.
		 *
		 * @api getName
		 * @return string
		 */
		public function getName(): string {
			return 'user_accounts';
		}

		/**
		 * Returns the revisions of the table.
		 *
		 * @api versionLog
		 * @return TableVersion[]
		 */
		public function versionLog(): array {
			$id = match ($this->type) {
				DatabaseType::MYSQL => 'id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY',
				DatabaseType::POSTGRESQL => 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
				DatabaseType::SQLITE => 'id INTEGER PRIMARY KEY AUTOINCREMENT',
				DatabaseType::MSSQL => 'id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY'
			};

			return [
				new TableVersion(1, ['CREATE TABLE user_accounts (' . $id . ', email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, flags INTEGER NOT NULL, registered BIGINT NOT NULL)'])
			];
		}
	}
